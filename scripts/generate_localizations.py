#!/usr/bin/env python3
"""Build audited UTF-8 Apple strings resources; no network or runtime translation."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'scripts/localization'
LANGUAGES = ['zh-Hans', 'zh-Hant', 'en', 'ja', 'ko', 'es', 'fr', 'de', 'it', 'pt-BR', 'ru', 'ar', 'hi', 'id', 'th', 'vi']
keys = json.loads((SOURCE / 'source_keys.json').read_text())
translations = {}
for number, line in enumerate((SOURCE / 'catalog.tsv').read_text().splitlines(), 1):
    if not line.strip(): continue
    fields = line.split('|')
    assert len(fields) == 16, (number, len(fields))
    source = keys[int(fields[0])] if fields[0].isdigit() else fields[0]
    assert source not in translations, ('Duplicate source', source)
    assert all(fields[1:]), ('Empty translation', source)
    tokens = re.compile(r"%(?:[0-9]+\$)?[+0-9.]*[@df]")
    for value in fields[1:]:
        assert len(tokens.findall(value)) == len(tokens.findall(source)), ('Format mismatch', source, value)
        assert all(token == '%@' for token in tokens.findall(value)), ('Use string substitutions for captured values', source)
    translations[source] = [source] + [v.replace(r"\n", "\n") for v in fields[1:]]

# Technical diagnostics remain intact in stored capture notes and logs. Their
# localized presentation uses concise, actionable categories without claiming
# an original exists when the source only says capture failed.
aliases = {}
def alias(target, *indices):
    target = keys[target] if isinstance(target, int) else target
    assert target in translations, target
    for index in indices:
        source = keys[index]
        assert source not in translations and source not in aliases, source
        aliases[source] = target

