def write_strings(path, values):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('// Generated by scripts/generate_localizations.py. Edit scripts/localization/catalog.tsv.\n' + ''.join(
        json.dumps(k, ensure_ascii=False) + ' = ' + json.dumps(v, ensure_ascii=False) + ';\n' for k,v in sorted(values.items())))

for column, language in enumerate(LANGUAGES):
    folder = ROOT / 'Shared/Resources' / (language + '.lproj')
    write_strings(folder / 'Localizable.strings', {k:v[column] for k,v in translations.items()})
    write_strings(folder / 'InfoPlist.strings', {'CFBundleDisplayName':'ArkCam', **{k:translations[v][column] for k,v in privacy.items()}})

(ROOT / 'scripts/localization/coverage.json').write_text(json.dumps({
    'languages': LANGUAGES, 'keys': len(translations),
    'presentationAliases': aliases,
    'nonUIExclusions': {keys[i]: 'URL, stable export basename, or software metadata' for i in sorted(excluded)},
}, ensure_ascii=False, indent=2) + '\n')
print(f'Generated {len(translations)} strings + {len(privacy)} permission descriptions in {len(LANGUAGES)} languages.')
